import { flatten, type FlatAction, type Ontology, type ResourceSpec } from "../ontology/dsl.js";
import { jsdoc, key, pascal, tsFields, tsType, zodExpr, zodFields } from "./fields.js";

const HEADER = `// GENERATED by the ontology in src/ontology/. Do not edit. Run \`npm run gen\`.\n`;

/** `event.get` → `EventGet`; `judgingRound.set` → `JudgingRoundSet`. */
const typeName = (a: FlatAction) => pascal(a.key.replace(/\./g, "_"));
const hasRequired = (fields: Record<string, { optional?: boolean }>) => Object.values(fields).some((f) => !f.optional);
const ident = (s: string) => /^[A-Za-z_$][\w$]*$/.test(s);

// ─── schemas.ts ───────────────────────────────────────────────────────

export function emitSchemas(o: Ontology): string {
  let out = `${HEADER}import { z } from "zod";\n\n// ─── Entities ───\n\n`;
  for (const e of Object.values(o.entities)) {
    out += jsdoc(e.description, "");
    out += `export interface ${e.name} {\n${tsFields(e.fields, "  ")}}\n`;
    out += `export const ${e.name}Schema: z.ZodType<${e.name}> = z.object({\n${zodFields(e.fields, "  ")}});\n\n`;
  }
  out += `// ─── Action inputs and outputs ───\n\n`;
  for (const a of flatten(o)) {
    const n = typeName(a);
    const call = chainOf(a);
    if (a.spec.input) {
      out += jsdoc(`Input for \`${call}\`.`, "");
      out += `export interface ${n}Input {\n${tsFields(a.spec.input, "  ")}}\n`;
    }
    // The wire schema validates key + input together; the caller-facing type is input only.
    out += `export const ${n}WireSchema = z.object({\n${zodFields(a.fullInput, "  ")}});\n`;
    out += `/** Everything the server receives for \`${call}\`: scope key, resource key, and input. */\nexport type ${n}Wire = z.infer<typeof ${n}WireSchema>;\n`;
    out += jsdoc(`Output of \`${call}\`. ${a.spec.output.description}`, "");
    out += `export type ${n}Output = ${tsType(a.spec.output)};\n`;
    out += `export const ${n}OutputSchema: z.ZodType<${n}Output> = ${zodExpr(a.spec.output)};\n\n`;
  }
  return out;
}

// ─── errors.ts ────────────────────────────────────────────────────────

export function emitErrors(o: Ontology): string {
  const seen = new Map<string, string>();
  for (const a of flatten(o)) for (const [name, e] of Object.entries(a.spec.errors)) if (!seen.has(name)) seen.set(name, e.description);
  let out = `${HEADER}import { BtError } from "../runtime.js";\n\nexport { BtError, ApiError, NotAuthenticatedError, InputError, ContractViolationError } from "../runtime.js";\n\n`;
  for (const [name, desc] of seen) {
    out += jsdoc(desc, "");
    out += `export class ${name}Error extends BtError {\n  override readonly name = "${name}Error";\n}\n\n`;
  }
  return out;
}

// ─── client.ts ────────────────────────────────────────────────────────

function actionDoc(o: Ontology, a: FlatAction): string {
  const errs = Object.entries(a.spec.errors).map(([en, e]) => `\`${en}Error\` (${e.status}) ${e.description}`);
  return [
    a.spec.description,
    ``,
    `Auth: \`${a.spec.auth}\` — ${o.roles[a.spec.auth]?.description ?? ""}`,
    `Route: \`${a.spec.route.method} ${a.spec.route.path}\``,
    ...(errs.length ? [`Throws: ${errs.join("; ")}`] : []),
  ].join("\n");
}

/** `(input: S.XInput)`, `(input: S.XInput = {})`, or `()`. */
function param(a: FlatAction): { sig: string; arg: string } {
  if (!a.spec.input || !Object.keys(a.spec.input).length) return { sig: "", arg: "{}" };
  const n = typeName(a);
  return { sig: hasRequired(a.spec.input) ? `input: S.${n}Input` : `input: S.${n}Input = {}`, arg: "input" };
}

/** `bt.judging(…).team(…).get` — how the call reads in prose and docs. */
export function chainOf(a: FlatAction): string {
  const r = a.resource;
  const scope = r.scope ? `${r.scope.name}(${Object.keys(r.scope.key).join(", ")}).` : "";
  if (a.level === "collection") return `bt.${scope}${r.plural}.${a.name}`;
  return Object.keys(r.key).length ? `bt.${scope}${r.singular}(${Object.keys(r.key).join(", ")}).${a.name}` : `bt.${scope}${r.singular}.${a.name}`;
}

export function emitClient(o: Ontology): string {
  const flat = flatten(o);
  const byKey = new Map(flat.map((a) => [a.key, a]));
  let out = `${HEADER}import { Runtime, type ActionMeta, type ClientConfig } from "../runtime.js";\nimport * as S from "./schemas.js";\nimport * as E from "./errors.js";\n\n`;

  out += `const meta = {\n`;
  for (const a of flat) {
    const r = a.spec.route;
    const errors = Object.entries(a.spec.errors).map(([en, e]) => `${e.status}: E.${en}Error`).join(", ");
    out += `  "${a.key}": {\n`;
    out += `    key: "${a.key}", method: "${r.method}", path: ${JSON.stringify(r.path)}, query: ${JSON.stringify(r.query ?? [])}, fixedQuery: ${JSON.stringify(r.fixedQuery ?? {})},\n`;
    out += `    auth: "${a.spec.auth}", input: S.${typeName(a)}WireSchema, output: S.${typeName(a)}OutputSchema, errors: { ${errors} },\n`;
    out += `  },\n`;
  }
  out += `} satisfies Record<string, ActionMeta>;\n\n`;

  // One resource → its collection object and/or its instance function, at a given indent,
  // with `chain` being the variables already bound by enclosing closures (scope key).
  const emitResource = (r: ResourceSpec, indent: string, chain: string[]): string => {
    let s = "";
    const collection = flat.filter((a) => a.resource === r && a.level === "collection");
    const instance = flat.filter((a) => a.resource === r && a.level === "instance");
    const keyNames = Object.keys(r.key);
    const merged = (vars: string[], hasInput: boolean) => (vars.length ? `{ ${vars.map(key).join(", ")}${hasInput ? ", ...input" : ""} }` : hasInput ? "input" : "{}");

    if (collection.length) {
      s += jsdoc(r.description, indent);
      s += `${indent}${key(r.plural!)}: {\n`;
      for (const a of collection) {
        const { sig, arg } = param(a);
        s += jsdoc(actionDoc(o, a), indent + "  ");
        s += `${indent}  ${key(a.name)}: (${sig}) => rt.call<S.${typeName(a)}Output>(meta["${a.key}"], ${merged(chain, arg === "input")}),\n`;
      }
      s += `${indent}},\n`;
    }
    if (instance.length || Object.keys(r.links).length) {
      const vars = [...chain, ...keyNames];
      const body = (inner: string) => {
        let b = "";
        for (const a of instance) {
          const { sig, arg } = param(a);
          b += jsdoc(actionDoc(o, a), inner);
          b += `${inner}${key(a.name)}: (${sig}) => rt.call<S.${typeName(a)}Output>(meta["${a.key}"], ${merged(vars, arg === "input")}),\n`;
        }
        for (const [lk, l] of Object.entries(r.links)) {
          const target = byKey.get(l.via)!;
          const mapping = Object.entries(l.map).map(([inF, keyF]) => `${key(inF)}: ${ident(keyF) ? keyF : `key_${keyF}`}`).join(", ");
          b += jsdoc(`${l.description}\n\nLink → \`${l.via}\`. One HTTP call.`, inner);
          b += `${inner}${key(lk)}: () => rt.call<S.${typeName(target)}Output>(meta["${l.via}"], { ${mapping} }),\n`;
        }
        return b;
      };
      s += jsdoc(r.description, indent);
      if (keyNames.length) {
        const sig = keyNames.map((k) => `${ident(k) ? k : `key_${k}`}: ${tsType(r.key[k]!)}`).join(", ");
        s += `${indent}${key(r.singular)}: (${sig}) => ({\n${body(indent + "  ")}${indent}}),\n`;
      } else {
        s += `${indent}${key(r.singular)}: {\n${body(indent + "  ")}${indent}},\n`;
      }
    }
    return s;
  };

  out += jsdoc(
    "Create a client. One per app, at startup. Every method is exactly one HTTP call to the BizTech API.\nSee README.md in this package for worked examples.",
    "",
  );
  out += `export function createClient(config: ClientConfig) {\n  const rt = new Runtime(config);\n  return {\n`;
  const unscoped = Object.values(o.resources).filter((r) => !r.scope);
  const scoped = new Map<string, ResourceSpec[]>();
  for (const r of Object.values(o.resources)) if (r.scope) scoped.set(r.scope.name, [...(scoped.get(r.scope.name) ?? []), r]);

  for (const r of unscoped) out += emitResource(r, "    ", []);
  for (const [name, rs] of scoped) {
    const scope = rs[0]!.scope!;
    const keyNames = Object.keys(scope.key);
    const sig = keyNames.map((k) => `${k}: ${tsType(scope.key[k]!)}`).join(", ");
    out += jsdoc(`${scope.description}\n\nEverything under \`bt.${name}(${keyNames.join(", ")})\` is served by the generated \`${rs[0]!.service}\` service.`, "    ");
    out += `    ${key(name)}: (${sig}) => ({\n`;
    for (const r of rs) out += emitResource(r, "      ", keyNames);
    out += `    }),\n`;
  }
  out += `  };\n}\n\nexport type BtClient = ReturnType<typeof createClient>;\n`;
  return out;
}

// ─── docs ─────────────────────────────────────────────────────────────

function fieldRows(fields: Record<string, { kind: string; optional?: boolean; nullable?: boolean; description: string }>): string {
  return Object.entries(fields)
    .map(([k, f]) => `| \`${k}\` | ${f.kind}${f.nullable ? " \\| null" : ""}${f.optional ? "?" : ""} | ${f.description.replace(/\|/g, "\\|")} |`)
    .join("\n");
}
const outLink = (f: { kind: string; entity?: string; items?: { kind: string; entity?: string } }): string =>
  f.kind === "ref" ? `[${f.entity}](./entities.md#${f.entity!.toLowerCase()})` : f.kind === "array" && f.items?.kind === "ref" ? `[${f.items.entity}](./entities.md#${f.items.entity!.toLowerCase()})[]` : f.kind;

export function emitDocs(o: Ontology): Record<string, string> {
  const files: Record<string, string> = {};
  const flat = flatten(o);
  let index = `# @ubc-biztech/sdk — reference\n\nGenerated from the ontology. Every fact here is also in the JSDoc; this is the same information for readers who are not in an editor.\n\n## Roles\n\n| Role | Meaning |\n|---|---|\n`;
  for (const [r, s] of Object.entries(o.roles)) index += `| \`${r}\` | ${s.description} |\n`;
  index += `\n## Resources\n\n`;
  for (const r of Object.values(o.resources)) {
    const acts = flat.filter((a) => a.resource === r);
    const chain = chainOf;
    const docName = r.scope ? `${r.scope.name}.${r.singular}` : r.singular;
    index += `- [\`${docName}\`](./${docName}.md) — ${acts.map((a) => `\`${chain(a)}\``).join(", ")}${Object.keys(r.links).length ? ` · links: ${Object.keys(r.links).map((l) => `\`${l}\``).join(", ")}` : ""}\n`;
    let md = `# \`${docName}\`\n\n${r.description}\n\n`;
    if (r.scope) md += `Scoped under \`bt.${r.scope.name}(${Object.keys(r.scope.key).join(", ")})\`: ${r.scope.description}${r.service !== "legacy" ? ` Served by the generated \`${r.service}\` service.` : ""}\n\n`;
    if (Object.keys(r.key).length) md += `**Key** (positional arguments of \`bt.${r.singular}(…)\`)\n\n| Field | Type | Description |\n|---|---|---|\n${fieldRows(r.key)}\n\n`;
    for (const a of acts) {
      const hasIn = a.spec.input && Object.keys(a.spec.input).length;
      md += `## \`${chain(a)}(${hasIn ? "input" : ""})\`\n\n${a.spec.description}\n\n- **Auth:** \`${a.spec.auth}\`\n- **Route:** \`${a.spec.route.method} ${a.spec.route.path}\`${a.spec.route.fixedQuery ? ` with \`?${new URLSearchParams(a.spec.route.fixedQuery)}\`` : ""}\n`;
      if (hasIn) md += `\n**Input**\n\n| Field | Type | Description |\n|---|---|---|\n${fieldRows(a.spec.input!)}\n`;
      md += `\n**Output:** ${outLink(a.spec.output)} — ${a.spec.output.description}\n`;
      const errs = Object.entries(a.spec.errors);
      if (errs.length) md += `\n**Errors**\n\n| Error | HTTP | When |\n|---|---|---|\n${errs.map(([en, e]) => `| \`${en}Error\` | ${e.status} | ${e.description} |`).join("\n")}\n`;
      md += `\n`;
    }
    const links = Object.entries(r.links);
    if (links.length) {
      md += `## Links\n\n| Call | Via | Description |\n|---|---|---|\n`;
      for (const [lk, l] of links) md += `| \`${chainOf({ resource: r, level: "instance", name: lk } as FlatAction)}()\` | \`${l.via}\` | ${l.description} |\n`;
      md += `\n`;
    }
    files[`${docName}.md`] = md;
  }
  index += `- [Entities](./entities.md)\n`;
  let ents = `# Entities\n\n`;
  for (const e of Object.values(o.entities)) {
    ents += `## ${e.name}\n\n${e.description}\n\n`;
    if (e.storage) ents += `Storage: table \`${e.storage.table}\`, pk \`${e.storage.pk}\`${e.storage.sk ? `, sk \`${e.storage.sk}\`` : ""}.\n\n`;
    ents += `| Field | Type | Description |\n|---|---|---|\n${fieldRows(e.fields)}\n\n`;
  }
  files["entities.md"] = ents;
  files["README.md"] = index;
  return files;
}

/** Canonical JSON of the declaration; the semver check diffs two of these. */
export function snapshot(o: Ontology): string {
  return JSON.stringify(o, null, 2) + "\n";
}



// ─── server/<service>.ts ──────────────────────────────────────────────

/** `judging.teams.list` → `teamsList`; `judging.team.get` → `teamGet`. Scope prefix dropped. */
const implName = (a: FlatAction) => {
  const parts = a.key.split(".");
  const local = a.resource.scope ? parts.slice(1) : parts;
  return local[0]! + local.slice(1).map(pascal).join("");
};

/**
 * One file per generated service: the route table the server runtime needs, the typed
 * implementation contract the service must satisfy, and createHandler().
 */
export function emitServer(o: Ontology, service: string, actions: FlatAction[]): string {
  const scope = actions[0]!.resource.scope;
  const scopeType = scope ? `{ ${Object.entries(scope.key).map(([k, f]) => `${key(k)}: ${tsType(f)}`).join("; ")} }` : "Record<string, never>";
  const scopeFrom = scope ? `(p) => ({ ${Object.keys(scope.key).map((k) => `${key(k)}: p[${JSON.stringify(k)}] as ${tsType(scope.key[k]!)}`).join(", ")} })` : `() => ({})`;

  let out = `${HEADER}import { createRouter, type ActionError, type BaseImpl, type Ctx, type RouteMeta, type Roles } from "../runtime.js";\nimport * as S from "../../client/generated/schemas.js";\n\n`;
  out += `export { ActionError } from "../runtime.js";\n\n`;
  out += `/** Scope key every action in "${service}" receives. */\nexport type Scope = ${scopeType};\n\n`;

  out += `/** Roles, with implication, as declared in src/ontology/roles.ts. */\nexport const roles: Roles = ${JSON.stringify(Object.fromEntries(Object.entries(o.roles).map(([r, s]) => [r, { implies: s.implies ?? [] }])), null, 2)};\n\n`;

  out += `export const routes: readonly RouteMeta[] = [\n`;
  for (const a of actions) {
    const paramKinds = Object.fromEntries(
      Object.entries(a.fullInput)
        .filter(([k]) => a.spec.route.path.includes(`{${k}}`) || (a.spec.route.query ?? []).includes(k))
        .map(([k, f]) => [k, f.kind]),
    );
    out += `  {\n    key: "${a.key}", method: "${implName(a)}", http: "${a.spec.route.method}", path: ${JSON.stringify(a.spec.route.path)}, query: ${JSON.stringify(a.spec.route.query ?? [])},\n`;
    out += `    auth: "${a.spec.auth}", paramKinds: ${JSON.stringify(paramKinds)}, scopeFields: ${JSON.stringify(Object.keys(scope?.key ?? {}))},\n`;
    out += `    input: S.${typeName(a)}WireSchema, output: S.${typeName(a)}OutputSchema, errors: ${JSON.stringify(Object.fromEntries(Object.entries(a.spec.errors).map(([n, e]) => [n, e.status])))},\n  },\n`;
  }
  out += `];\n\n`;

  out += jsdoc(
    `What the "${service}" service must implement. One method per declared action; the input is the\nvalidated wire input (scope key + resource key + body/query), the return value is validated against\nthe declared output before it is sent. Throw \`new ActionError("<DeclaredName>", message)\` for a declared\nerror; any other throw is a 500.`,
    "",
  );
  out += `export interface Impl extends BaseImpl<Scope> {\n`;
  for (const a of actions) {
    const errs = Object.keys(a.spec.errors);
    out += jsdoc(`${a.spec.description}\n\nAuth: \`${a.spec.auth}\`.${errs.length ? ` May throw: ${errs.join(", ")}.` : ""}`, "  ");
    out += `  ${implName(a)}(ctx: Ctx<Scope>, input: S.${typeName(a)}Wire): Promise<S.${typeName(a)}Output>;\n`;
  }
  out += `}\n\n`;

  out += jsdoc(`Build the Lambda handler for "${service}". Wire it to \`ANY ${scope ? actions[0]!.spec.route.path.split("/{")[0] : "/" + service}/{proxy+}\`.`, "");
  out += `export function createHandler(impl: Impl, log?: (line: Record<string, unknown>) => void) {\n`;
  out += `  return createRouter<Scope, Impl>({ service: "${service}", routes, roles, scopeFrom: ${scopeFrom}, impl, log });\n}\n`;
  return out;
}
